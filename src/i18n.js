class SimpleI18n {
  constructor(translations) {
    this.translations = translations;
    this.locale = "ru";
    this.enableFallback = true;
    this.defaultLocale = "ru";

    // Инициализируем только на клиенте (в браузере или на телефоне)
    if (typeof window !== "undefined") {
      this.init();
    }
  }

  async init() {
    try {
      const savedLang = await AsyncStorage.getItem("appLanguage");
      if (savedLang && this.translations[savedLang]) {
        this.locale = savedLang;
      }
    } catch (e) {
      console.log("Ошибка загрузки языка:", e);
    }
  }

  async setLanguage(lang) {
    if (!this.translations[lang]) return;
    this.locale = lang;
    try {
      await AsyncStorage.setItem("appLanguage", lang);
    } catch (e) {
      console.log("Ошибка сохранения языка:", e);
    }
  }

  t(key) {
    const currentDict =
      this.translations[this.locale] || this.translations[this.defaultLocale];
    if (currentDict && currentDict[key]) {
      return currentDict[key];
    }
    const defaultDict = this.translations[this.defaultLocale];
    if (defaultDict && defaultDict[key]) {
      return defaultDict[key];
    }
    return key;
  }
}

const i18n = new SimpleI18n(translations);

export default i18n;
